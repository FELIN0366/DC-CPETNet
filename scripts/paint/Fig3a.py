"""
Plot Result 1.7 subgroup main figure: task-wise robustness across age, sex,
and disease-mechanism subgroups.

Input
-----
An Excel file generated by `build_subgroup_task_profile_tables.py`, containing
sheet `Fig_subgroup_task_profile_data` with columns such as:
    panel, panel_order, metric, metric_panel_order, subgroup_label,
    subgroup_order, task, task_order, mean, sd, errorbar_in_main,
    is_reference, line_color, line_style, marker,
    recommended_ymin, recommended_ymax

Final figure layout
-------------------
Figure X | Task-wise robustness across age, sex, and disease-mechanism subgroups.
- 3 columns: Age, Sex, T6 disease mechanism
- 2 rows: Accuracy, Macro-F1
- x-axis: t1, t2, t3, t4, t5, Mean
- subgroup lines: age/sex/t6 groups
- full overall holdout cohort: black dashed reference line in each panel
- error bars: only shown for the final Mean across t1-t5 point by default

Usage
-----
python plot_subgroup_task_profile_main.py \
  --input "xx_path" \
  --out_dir "xx_path"

Outputs
-------
- Fig_subgroup_task_profile_main.png
- Fig_subgroup_task_profile_main.pdf
- Fig_subgroup_task_profile_main.svg
- Fig_subgroup_task_profile_main.tiff
"""

