DEFAULT_INPUT = Path(
    r"xx_path"
)
DEFAULT_SHEET = "Fig_subgroup_task_profile_data"
DEFAULT_OUT_DIR = Path(
    r"xx_path"
)
DEFAULT_PREFIX = "Fig_subgroup_task_profile_main"

# Final task order used in the main figure.
TASK_ORDER = ["t1", "t2", "t3", "t4", "t5", "Mean across t1–t5"]
TASK_SHORT_LABEL = {
    "t1": "t1",
    "t2": "t2",
    "t3": "t3",
    "t4": "t4",
    "t5": "t5",
    "Mean across t1–t5": "Mean",
    "Mean across t1-t5": "Mean",
}

# Panel and metric orders.
PANEL_ORDER = ["Age", "Sex", "T6 disease mechanism"]
PANEL_TITLE = {
    "Age": "Age subgroup",
    "Sex": "Sex subgroup",
    "T6 disease mechanism": "Disease-mechanism subgroup",
}
PANEL_LETTER = {
    "Age": "a",
    "Sex": "b",
    "T6 disease mechanism": "c",
}
METRIC_ORDER = ["Accuracy", "Macro-F1"]

# Y-axis limits; rows share the same limits across three columns.
DEFAULT_YLIM = {
    "Accuracy": (0.68, 1.01),
    "Macro-F1": (0.45, 1.01),
}

# Fallback line styles if the input sheet does not provide style columns.
FALLBACK_COLORS = {
    # Age
    "Age <30": "#A6C8E8",
    "Age 30-39": "#BBD3E9",
    "Age 40-49": "#6FA8DC",
    "Age 50-59": "#2F75B5",
    "Age 60-69": "#1F4E79",
    "Age ≥70": "#1F4E79",
    # Sex
    "Female": "#9B59B6",
    "Male": "#2CA6A4",
    # T6
    "CMP": "#2C7FB8",
    "HTx": "#70AD47",
    "IHD": "#F4B183",
    "PVD": "#C55A9E",
}
FALLBACK_PANEL_GROUP_ORDER = {
    "Age": [ "Age <30", "Age 30-39", "Age 40-49", "Age 50-59", "Age 60-69", "Age ≥70"],
    "Sex": ["Female", "Male"],
    "T6 disease mechanism": ["CMP", "HTx", "IHD", "PVD"],
}


