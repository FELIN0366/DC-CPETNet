def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Plot subgroup task-profile main figure for Result 1.7."
    )
    parser.add_argument(
        "--input",
        type=str,
        default=str(DEFAULT_INPUT),
        help="Input Excel generated by build_subgroup_task_profile_tables.py.",
    )
    parser.add_argument(
        "--sheet",
        type=str,
        default=DEFAULT_SHEET,
        help="Sheet name containing Fig_subgroup_task_profile_data.",
    )
    parser.add_argument(
        "--out_dir",
        type=str,
        default=str(DEFAULT_OUT_DIR),
        help="Output directory for figures.",
    )
    parser.add_argument(
        "--prefix",
        type=str,
        default=DEFAULT_PREFIX,
        help="Output figure prefix.",
    )
    parser.add_argument(
        "--dpi",
        type=int,
        default=600,
        help="DPI for PNG/TIFF outputs.",
    )
    parser.add_argument(
        "--font_family",
        type=str,
        default="Arial",
        help="Preferred font family. Falls back to DejaVu Sans if unavailable.",
    )
    parser.add_argument(
        "--no_errorbar",
        action="store_true",
        help="Disable error bars at the Mean across t1-t5 point.",
    )
    parser.add_argument(
        "--fig_width",
        type=float,
        default=14.2,
        help="Figure width in inches.",
    )
    parser.add_argument(
        "--fig_height",
        type=float,
        default=7.2,
        help="Figure height in inches.",
    )
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    input_path = Path(args.input)
    out_dir = Path(args.out_dir)

    print(f"[Input] {input_path}")
    print(f"[Sheet] {args.sheet}")

    df = load_profile_data(input_path, args.sheet)
    print(f"[Loaded] rows={len(df)}, panels={df['panel'].nunique()}, metrics={df['metric'].nunique()}")

    # Basic check: each panel should have Accuracy and Macro-F1.
    check = df.groupby(["panel", "metric"]).size().unstack(fill_value=0)
    print("[Panel x metric counts]")
    print(check)

    plot_main_figure(
        df=df,
        out_dir=out_dir,
        prefix=args.prefix,
        dpi=args.dpi,
        show_errorbar=not args.no_errorbar,
        font_family=args.font_family,
        fig_width=args.fig_width,
        fig_height=args.fig_height,
    )


if __name__ == "__main__":
    main()

