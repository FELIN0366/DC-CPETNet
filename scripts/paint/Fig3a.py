def configure_matplotlib(font_family: str = "Arial") -> None:
    plt.rcParams.update({
        "font.family": "sans-serif",
        "font.sans-serif": [font_family, "DejaVu Sans", "Liberation Sans"],
        "pdf.fonttype": 42,
        "ps.fonttype": 42,
        "axes.linewidth": 1.0,
        "axes.labelsize": 10.5,
        "axes.titlesize": 12,
        "xtick.labelsize": 9.5,
        "ytick.labelsize": 9.5,
        "legend.fontsize": 8.8,
        "figure.dpi": 120,
        "savefig.dpi": 600,
    })


def prettify_axis(ax: plt.Axes, metric: str, show_xlabel: bool = True) -> None:
    x_positions = np.arange(len(TASK_ORDER))
    ax.set_xticks(x_positions)
    ax.set_xticklabels([TASK_SHORT_LABEL.get(t, t) for t in TASK_ORDER])
    ax.set_xlim(-0.35, len(TASK_ORDER) - 0.65)
    ax.axvline(4.5, color="#D0D0D0", linestyle="--", linewidth=0.9, zorder=0)

    # Row-wise y-axis limits.
    ymin, ymax = DEFAULT_YLIM.get(metric, (0.0, 1.0))
    ax.set_ylim(ymin, ymax)

    ax.set_ylabel(metric, fontweight="bold")
    if show_xlabel:
        ax.set_xlabel("Task", fontweight="bold")
    else:
        ax.set_xlabel("")

    ax.grid(axis="y", color="#EAEAEA", linewidth=0.8)
    ax.grid(axis="x", visible=False)
    ax.spines["top"].set_visible(False)
    ax.spines["right"].set_visible(False)


    ax.tick_params(axis="both", direction="out", length=3.5, width=0.9)

    # 强制所有子图都显示 x 轴刻度标签，包括上排 Accuracy 子图
    ax.tick_params(
        axis="x",
        labelsize=11.5,
        labelbottom=True,
        bottom=True,
    )

    # 强制所有子图都显示 y 轴刻度标签，包括 b/c 两列
    ax.tick_params(
        axis="y",
        labelsize=11.5,
        labelleft=True,
        left=True,
    )


def make_panel_legend(ax: plt.Axes, handles: List[Line2D], ncol: int) -> None:
    ax.legend(
        handles=handles,
        loc="center",
        bbox_to_anchor=(0.5, 0.93),
        frameon=False,
        ncol=ncol,
        fontsize=10,
        handlelength=2.2,
        columnspacing=1.0,
        borderaxespad=0.0,
    )


def plot_single_axis(
    ax: plt.Axes,
    df: pd.DataFrame,
    panel_name: str,
    metric: str,
    show_errorbar: bool = True,
    line_width: float = 2.0,
    marker_size: float = 4.8,
) -> List[Line2D]:
    panel_metric_df = df[(df["panel"] == panel_name) & (df["metric"] == metric)].copy()
    if panel_metric_df.empty:
        raise ValueError(f"No data for panel={panel_name}, metric={metric}")

    legend_handles: List[Line2D] = []
    labels = ordered_groups(panel_metric_df, panel_name)

    # Plot reference first, then subgroups.
    for label in labels:
        gdf = panel_metric_df[panel_metric_df["subgroup_label"].astype(str) == label].copy()
        if gdf.empty:
            continue
        gdf = gdf.sort_values("task_order")
        color, ls, marker, is_ref = get_style(gdf, label)
        x, y, yerr = values_for_group(gdf)

        z = 2 if is_ref else 3
        alpha = 0.92 if is_ref else 1.0
        lw = line_width * (0.90 if is_ref else 1.00)
        ms = marker_size * (0.92 if is_ref else 1.00)

        ax.plot(
            x, y,
            linestyle=ls,
            color=color,
            marker=marker,
            markersize=ms,
            markerfacecolor="white" if is_ref else color,
            markeredgecolor=color,
            markeredgewidth=1.2,
            linewidth=lw,
            alpha=alpha,
            zorder=z,
        )

        if show_errorbar:
            # Only show error bar at Mean point by default.
            mean_idx = TASK_ORDER.index("Mean across t1–t5")
            if np.isfinite(y[mean_idx]) and np.isfinite(yerr[mean_idx]):
                ax.errorbar(
                    [x[mean_idx]], [y[mean_idx]], yerr=[yerr[mean_idx]],
                    fmt="none",
                    ecolor=color,
                    elinewidth=1.2,
                    capsize=2.8,
                    capthick=1.1,
                    alpha=0.90,
                    zorder=z + 1,
                )

        legend_handles.append(
            Line2D(
                [0], [0],
                color=color,
                linestyle=ls,
                marker=marker,
                markersize=ms,
                markerfacecolor="white" if is_ref else color,
                markeredgecolor=color,
                linewidth=lw,
                label=str(label),
            )
        )

    return legend_handles


def plot_main_figure(
    df: pd.DataFrame,
    out_dir: Path,
    prefix: str,
    dpi: int = 600,
    show_errorbar: bool = True,
    font_family: str = "Arial",
    fig_width: float = 14.2,
    fig_height: float = 7.2,
) -> List[Path]:
    configure_matplotlib(font_family=font_family)
    out_dir.mkdir(parents=True, exist_ok=True)

    fig, axes = plt.subplots(
        nrows=2,
        ncols=3,
        figsize=(fig_width, fig_height),
        sharex=True,
        sharey="row",
        constrained_layout=False,
    )

    for col, panel_name in enumerate(PANEL_ORDER):
        for row, metric in enumerate(METRIC_ORDER):
            ax = axes[row, col]
            handles = plot_single_axis(
                ax,
                df=df,
                panel_name=panel_name,
                metric=metric,
                show_errorbar=show_errorbar,
            )
            prettify_axis(ax, metric=metric, show_xlabel=(row == 1))

            if row == 0:
                # 小标题保留，但删除 a/b/c
                title = PANEL_TITLE.get(panel_name, panel_name)
                ax.set_title(title, loc="center", fontweight="bold", fontsize=12.5,pad=10)

                n_groups = max(1, len(handles))

                # Age 组别较多，保留两行；T6 强制一排显示
                if panel_name == "Age":
                    ncol = 3
                elif panel_name == "T6 disease mechanism":
                    ncol = n_groups
                else:
                    ncol = n_groups

                make_panel_legend(ax, handles, ncol=ncol)

            # 不再隐藏 b/c 的 y 轴数值
            ax.tick_params(axis="y", labelleft=True)

            # 如果只想左侧保留 y 轴标题，保留下面这句；
            # 如果你希望 b/c 也显示 Accuracy / Macro-F1，则注释掉这三行。
            if col != 0:
                ax.set_ylabel("")

    # A light global title. Comment out if you prefer no title in paper figures.
    # fig.suptitle(
    #     "Task-wise robustness across age, sex, and disease-mechanism subgroups",
    #     y=0.985,
    #     fontsize=13.5,
    #     fontweight="bold",
    # )

    # fig.text(
    #     0.5,
    #     0.015,
    #     "t1, CPET functional class; t2, exercise capacity; t3, exercise ECG interpretation; "
    #     "t4, ventilatory function; t5, heart-rate reserve. Mean denotes mean across t1–t5.",
    #     ha="center",
    #     va="bottom",
    #     fontsize=8.8,
    # )

    plt.subplots_adjust(
        left=0.065,
        right=0.985,
        top=0.875,
        bottom=0.115,
        wspace=0.18,
        hspace=0.18,
    )

    saved_paths: List[Path] = []
    for ext in ["png", "pdf", "svg", "tiff"]:
        path = out_dir / f"{prefix}.{ext}"
        if ext in {"png", "tiff"}:
            fig.savefig(path, dpi=dpi, bbox_inches="tight")
        else:
            fig.savefig(path, bbox_inches="tight")
        saved_paths.append(path)
        print(f"[Saved] {path}")

    plt.close(fig)
    return saved_paths


