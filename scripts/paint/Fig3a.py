def parse_bool(value) -> bool:
    """Robust boolean parser for values imported from Excel."""
    if isinstance(value, bool):
        return value
    if pd.isna(value):
        return False
    s = str(value).strip().lower()
    return s in {"true", "1", "yes", "y", "t"}


def normalize_task_name(task: str) -> str:
    """Normalize possible hyphen variants in the mean label."""
    s = str(task).strip()
    if s in {"Mean", "mean", "Mean across t1-t5", "Mean across t1–t5"}:
        return "Mean across t1–t5"
    return s


def ensure_required_columns(df: pd.DataFrame) -> None:
    required = ["panel", "metric", "subgroup_label", "task", "mean"]
    missing = [c for c in required if c not in df.columns]
    if missing:
        raise ValueError(
            "Input sheet is missing required columns: " + ", ".join(missing)
        )


def load_profile_data(xlsx_path: Path, sheet_name: str) -> pd.DataFrame:
    if not xlsx_path.exists():
        raise FileNotFoundError(f"Input Excel not found: {xlsx_path}")

    df = pd.read_excel(xlsx_path, sheet_name=sheet_name)
    ensure_required_columns(df)

    df = df.copy()
    df["task"] = df["task"].apply(normalize_task_name)
    df["mean"] = pd.to_numeric(df["mean"], errors="coerce")
    if "sd" in df.columns:
        df["sd"] = pd.to_numeric(df["sd"], errors="coerce")
    else:
        df["sd"] = np.nan

    if "task_order" not in df.columns:
        order_map = {t: i + 1 for i, t in enumerate(TASK_ORDER)}
        df["task_order"] = df["task"].map(order_map)
    if "subgroup_order" not in df.columns:
        df["subgroup_order"] = np.nan
    if "metric_panel_order" not in df.columns:
        df["metric_panel_order"] = df["metric"].map({"Accuracy": 1, "Macro-F1": 2})
    if "panel_order" not in df.columns:
        df["panel_order"] = df["panel"].map({p: i + 1 for i, p in enumerate(PANEL_ORDER)})
    if "is_reference" not in df.columns:
        df["is_reference"] = df["subgroup_label"].astype(str).str.contains("Full", case=False, na=False)
    if "errorbar_in_main" not in df.columns:
        df["errorbar_in_main"] = df["task"].eq("Mean across t1–t5")
    if "line_color" not in df.columns:
        df["line_color"] = df["subgroup_label"].map(FALLBACK_COLORS).fillna("#666666")
    if "line_style" not in df.columns:
        df["line_style"] = np.where(df["is_reference"].apply(parse_bool), "--", "-")
    if "marker" not in df.columns:
        df["marker"] = "o"

    # Keep only final main figure metrics and task order.
    df = df[df["metric"].isin(METRIC_ORDER)]
    df = df[df["task"].isin(TASK_ORDER)]

    return df


def ordered_groups(panel_df: pd.DataFrame, panel_name: str) -> List[str]:
    """Return subgroup labels ordered by subgroup_order, with fallback order."""
    tmp = (
        panel_df[["subgroup_label", "subgroup_order"]]
        .drop_duplicates()
        .copy()
    )
    tmp["subgroup_order"] = pd.to_numeric(tmp["subgroup_order"], errors="coerce")

    if tmp["subgroup_order"].notna().any():
        tmp = tmp.sort_values(["subgroup_order", "subgroup_label"])
        labels = tmp["subgroup_label"].astype(str).tolist()
    else:
        present = set(tmp["subgroup_label"].astype(str))
        fallback = [g for g in FALLBACK_PANEL_GROUP_ORDER.get(panel_name, []) if g in present]
        rest = sorted(list(present - set(fallback)))
        labels = fallback + rest

    # Ensure Full cohort appears first if available.
    full_like = [g for g in labels if str(g).lower() == "full cohort"]
    if full_like:
        labels = full_like + [g for g in labels if g not in full_like]
    return labels


def get_style(group_df: pd.DataFrame, group_label: str) -> Tuple[str, str, str, bool]:
    """Read color/style/marker/reference flag from group rows."""
    row = group_df.iloc[0]
    color = row.get("line_color", FALLBACK_COLORS.get(group_label, "#666666"))
    if pd.isna(color) or str(color).strip() == "":
        color = FALLBACK_COLORS.get(group_label, "#666666")

    is_ref = parse_bool(row.get("is_reference", group_label == "Full cohort"))
    line_style = row.get("line_style", "--" if is_ref else "-")
    if pd.isna(line_style) or str(line_style).strip() == "":
        line_style = "--" if is_ref else "-"

    marker = row.get("marker", "o")
    if pd.isna(marker) or str(marker).strip() == "":
        marker = "o"

    return str(color), str(line_style), str(marker), is_ref


def values_for_group(group_df: pd.DataFrame) -> Tuple[np.ndarray, np.ndarray, np.ndarray]:
    """Return x, y, sd arrays in final task order."""
    task_to_x = {t: i for i, t in enumerate(TASK_ORDER)}
    xs, ys, yerrs = [], [], []
    for task in TASK_ORDER:
        sub = group_df[group_df["task"] == task]
        if sub.empty:
            xs.append(task_to_x[task])
            ys.append(np.nan)
            yerrs.append(np.nan)
            continue
        row = sub.iloc[0]
        xs.append(task_to_x[task])
        ys.append(float(row["mean"]) if pd.notna(row["mean"]) else np.nan)
        yerrs.append(float(row["sd"]) if pd.notna(row.get("sd", np.nan)) else np.nan)
    return np.asarray(xs), np.asarray(ys), np.asarray(yerrs)


