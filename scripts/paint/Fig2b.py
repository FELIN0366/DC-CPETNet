# 从上到下为 T6-Ctx → αβ-Routing → β-Experts → 9P-Prior
DISPLAY_ORDER = [
    "w/o T6-Ctx",
    "w/o αβ-Routing",
    "w/o β-Experts",
    "w/o 9P-Prior",
]

EXPERIMENT_DISPLAY_NAME = {
    "E1": "w/o T6-Ctx",
    "E2": "w/o αβ-Routing",
    "E3": "w/o β-Experts",
    "E4": "w/o 9P-Prior",
    "S6": "w/o 9P-Prior",
}

EXPERIMENT_FULL_NAME = {
    "E1": "w/o T6 disease-context module",
    "E2": "w/o dual-trunk routing",
    "E3": "w/o Beta expert decomposition",
    "E4": "w/o nine-panel prior-guided chain",
    "S6": "w/o nine-panel prior-guided chain",
}


